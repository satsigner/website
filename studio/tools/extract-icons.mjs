/* components/icons/SSIcon*.tsx (react-native-svg) -> generated/icons.js
   JSX is walked with the TS AST and serialised as plain SVG. Original colours are kept
   for fidelity; `{color}`-style props become currentColor. */

import fs from 'node:fs'
import path from 'node:path'
import { kebab, writeOut } from './lib.mjs'

const KEEP_CAMEL = new Set(['viewBox', 'gradientUnits', 'gradientTransform', 'patternUnits', 'preserveAspectRatio', 'stdDeviation', 'clipPathUnits'])
const COLOR_ATTRS = new Set(['fill', 'stroke', 'stop-color', 'color'])

export function extractIcons({ ts, appDir, outDir }) {
  const dir = path.join(appDir, 'components/icons')
  const files = fs.readdirSync(dir).filter((f) => /^SSIcon.*\.tsx$/.test(f)).sort()
  const icons = {}
  const warnings = []

  for (const file of files) {
    const name = file.replace(/^SSIcon/, '').replace(/\.tsx$/, '')
    const sf = ts.createSourceFile(file, fs.readFileSync(path.join(dir, file), 'utf8'), ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX)
    let root
    const find = (node) => {
      if (root) return
      if ((ts.isJsxElement(node) || ts.isJsxSelfClosingElement(node)) && tagName(ts, node) === 'Svg') root = node
      else ts.forEachChild(node, find)
    }
    find(sf)
    if (!root) { warnings.push(`${file}: no <Svg> root`); continue }
    icons[key(name)] = serialize(ts, root, warnings, file, fileConsts(ts, sf))
  }

  const body = Object.entries(icons).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(',\n')
  writeOut(path.join(outDir, 'icons.js'),
    `/* GENERATED by studio/tools/extract-icons.mjs from apps/mobile/components/icons. Do not edit. */\n\nconst ssIcons = {\n${body}\n}\n`)
  return { count: Object.keys(icons).length, warnings }
}

const key = (name) => name.charAt(0).toLowerCase() + name.slice(1)

function tagName(ts, node) {
  const el = ts.isJsxElement(node) ? node.openingElement : node
  return el.tagName.getText()
}

function serialize(ts, node, warnings, file, consts) {
  if (ts.isJsxText(node)) return node.text.trim()
  if (ts.isJsxExpression(node)) return '' // dynamic children are dropped
  if (ts.isJsxFragment(node)) return node.children.map((c) => serialize(ts, c, warnings, file, consts)).join('')
  if (!ts.isJsxElement(node) && !ts.isJsxSelfClosingElement(node)) return ''

  const el = ts.isJsxElement(node) ? node.openingElement : node
  const rnTag = el.tagName.getText()
  const tag = rnTag === 'Svg' ? 'svg' : rnTag.charAt(0).toLowerCase() + rnTag.slice(1)
  const attrs = []
  for (const a of el.attributes.properties) {
    if (!ts.isJsxAttribute(a)) continue
    const raw = a.name.getText()
    if (rnTag === 'Svg' && (raw === 'width' || raw === 'height')) continue
    const name = KEEP_CAMEL.has(raw) ? raw : kebab(raw)
    let value = literal(ts, a.initializer, consts)
    if (value === undefined) {
      if (COLOR_ATTRS.has(name)) value = 'currentColor'
      else if (name === 'stroke-width') value = '1'
      else { warnings.push(`${file}: dropped dynamic ${raw}`); continue }
    }
    attrs.push(`${name}="${String(value).replace(/"/g, '&quot;')}"`)
  }
  if (rnTag === 'Svg') attrs.push('fill="none"', 'xmlns="http://www.w3.org/2000/svg"')
  const uniq = [...new Map(attrs.map((a) => [a.split('=')[0], a])).values()]
  const kids = ts.isJsxElement(node) ? node.children.map((c) => serialize(ts, c, warnings, file, consts)).join('') : ''
  return kids ? `<${tag} ${uniq.join(' ')}>${kids}</${tag}>` : `<${tag} ${uniq.join(' ')}/>`
}

function literal(ts, init, consts) {
  if (!init) return 'true'
  if (ts.isStringLiteral(init)) return init.text
  if (ts.isJsxExpression(init) && init.expression) return expr(ts, init.expression, consts)
  return undefined
}

function expr(ts, e, consts) {
  if (ts.isStringLiteral(e) || ts.isNoSubstitutionTemplateLiteral(e) || ts.isNumericLiteral(e)) return e.text
  if (ts.isPrefixUnaryExpression(e) && ts.isNumericLiteral(e.operand)) return `-${e.operand.text}`
  if (ts.isIdentifier(e) && e.text in consts) return consts[e.text]
  if (ts.isTemplateExpression(e)) {
    let s = e.head.text
    for (const span of e.templateSpans) {
      const v = expr(ts, span.expression, consts)
      if (v === undefined) return undefined
      s += v + span.literal.text
    }
    return s
  }
  return undefined
}

// Top-level and in-function `const X = <literal>` declarations, resolved in order.
function fileConsts(ts, sf) {
  const consts = {}
  const visit = (node) => {
    if (ts.isVariableDeclaration(node) && ts.isIdentifier(node.name) && node.initializer) {
      const v = expr(ts, node.initializer, consts)
      if (v !== undefined) consts[node.name.text] = v
    }
    ts.forEachChild(node, visit)
  }
  visit(sf)
  return consts
}
