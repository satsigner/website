/* styles/*.ts -> generated/tokens.css */

import path from 'node:path'
import { kebab, writeOut } from './lib.mjs'

function flatten(prefix, value, out) {
  if (value == null || typeof value === 'function') return
  if (typeof value === 'object') {
    for (const k of Object.keys(value).sort(numericFirst)) flatten(`${prefix}-${kebab(k)}`, value[k], out)
    return
  }
  const isNumber = typeof value === 'number'
  const unitless = /font-weight|opacity|flex|z-index|ratio/.test(prefix)
  out.push(`  ${prefix}: ${isNumber && !unitless ? `${value}px` : value};`)
}

function numericFirst(a, b) {
  const na = Number(a), nb = Number(b)
  if (!isNaN(na) && !isNaN(nb)) return na - nb
  return String(a).localeCompare(String(b))
}

export function extractTokens({ styles, outDir }) {
  const sections = []
  for (const [group, mod] of Object.entries(styles)) {
    const lines = []
    for (const k of Object.keys(mod).sort()) {
      // Colours keep their bare names (--white, --gray-100) to match the hand-written tokens.css.
      const prefix = group === 'Colors' ? `-` : `--${kebab(group)}`
      flatten(group === 'Colors' ? `-${prefix}${kebab(k)}` : `${prefix}-${kebab(k)}`, mod[k], lines)
    }
    sections.push(`  /* ${group} */\n${lines.join('\n')}`)
  }
  const css = `/* GENERATED by studio/tools/extract-tokens.mjs from apps/mobile/styles. Do not edit. */\n\n:root {\n${sections.join('\n\n')}\n}\n`
  writeOut(path.join(outDir, 'tokens.css'), css)
}
