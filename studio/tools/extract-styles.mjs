/* StyleSheet.create({...}) in components/, layouts/ and app/ -> generated/styles.css
   Class names: .<File>__<key>, e.g. .SSButton__buttonBase. Values that reference
   Colors/Sizes/Layout are evaluated against the real style modules; colours become token vars. */

import fs from 'node:fs'
import path from 'node:path'
import vm from 'node:vm'
import { colorIndex, kebab, walk, writeOut } from './lib.mjs'

const ABS = { position: 'absolute', left: 0, right: 0, top: 0, bottom: 0 }
const HOLE = new Proxy(function () {}, { get: (_, k) => (k === Symbol.toPrimitive ? () => NaN : HOLE), apply: () => HOLE })

const UNITLESS = new Set(['flex', 'flexGrow', 'flexShrink', 'opacity', 'zIndex', 'fontWeight', 'aspectRatio'])
const EXPAND = {
  paddingHorizontal: ['padding-left', 'padding-right'],
  paddingVertical: ['padding-top', 'padding-bottom'],
  marginHorizontal: ['margin-left', 'margin-right'],
  marginVertical: ['margin-top', 'margin-bottom']
}
const SKIP = new Set(['shadowOffset', 'shadowRadius', 'shadowOpacity', 'shadowColor', 'elevation', 'tintColor', 'includeFontPadding', 'textAlignVertical', 'resizeMode'])

export function extractStyles({ ts, appDir, outDir, styles }) {
  const colors = colorIndex(styles.Colors)
  const files = ['components', 'layouts', 'app'].flatMap((d) => walk(path.join(appDir, d), (f) => f.endsWith('.tsx') && !f.endsWith('.stories.tsx')))
  const blocks = []
  const warnings = []
  let rules = 0

  for (const file of files) {
    const src = fs.readFileSync(file, 'utf8')
    if (!src.includes('StyleSheet.create')) continue
    const sf = ts.createSourceFile(file, src, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX)
    const scope = cls(path.relative(appDir, file))
    const consts = localConsts(ts, sf)
    const visit = (node) => {
      if (ts.isCallExpression(node) && node.expression.getText() === 'StyleSheet.create' && node.arguments[0]) {
        let obj
        try {
          obj = evaluate(ts, node.arguments[0].getText(), styles, consts)
        } catch (e) {
          warnings.push(`${path.relative(appDir, file)}: ${e.message}`)
          return
        }
        const out = []
        for (const [name, style] of Object.entries(obj)) {
          if (!style || typeof style !== 'object') continue
          out.push(`.${scope}__${name} {\n${decls(style, colors).join('\n')}\n}`)
          rules++
        }
        if (out.length) blocks.push(`/* ${path.relative(appDir, file)} */\n${out.join('\n')}`)
      }
      ts.forEachChild(node, visit)
    }
    visit(sf)
  }

  writeOut(path.join(outDir, 'styles.css'),
    `/* GENERATED by studio/tools/extract-styles.mjs. Reference CSS for porting; do not edit. */\n\n${blocks.join('\n\n')}\n`)
  return { rules, warnings }
}

// app/(authenticated)/foo/[id].tsx -> "app-foo-id"; components/SSButton.tsx -> "SSButton"
function cls(rel) {
  const noExt = rel.replace(/\.tsx$/, '')
  if (noExt.startsWith('components/') || noExt.startsWith('layouts/')) return noExt.split('/').slice(1).join('-')
  return noExt.replace(/\([^)]*\)\/?/g, '').replace(/[[\]]/g, '').replace(/[^A-Za-z0-9]+/g, '-').replace(/-+$/, '')
}

// Simple top-level `const X = <literal>` values the style object may use.
function localConsts(ts, sf) {
  const out = {}
  for (const stmt of sf.statements) {
    if (!ts.isVariableStatement(stmt)) continue
    for (const d of stmt.declarationList.declarations) {
      if (!d.initializer || !ts.isIdentifier(d.name)) continue
      const i = d.initializer
      if (ts.isNumericLiteral(i)) out[d.name.text] = Number(i.text)
      else if (ts.isStringLiteral(i)) out[d.name.text] = i.text
    }
  }
  return out
}

function evaluate(ts, text, styles, consts) {
  const js = ts.transpileModule(`module.exports = (${text})`, { compilerOptions: { target: ts.ScriptTarget.ES2020 } }).outputText
  const module = {}
  const StyleSheet = { hairlineWidth: 1, absoluteFill: ABS, absoluteFillObject: ABS }
  const base = { module, ...styles, ...consts, StyleSheet, Platform: { OS: 'ios', select: (o) => o.ios ?? o.default } }
  // Unknown identifiers resolve to a hole that tolerates property access; holes are dropped later.
  const ctx = new Proxy(base, {
    has: () => true,
    get: (t, k) => (k in t ? t[k] : k === Symbol.unscopables ? undefined : k in globalThis ? globalThis[k] : HOLE)
  })
  vm.runInNewContext(`with (ctx) { ${js} }`, { ctx })
  return module.exports
}

function decls(style, colors) {
  const out = []
  for (const [k, v] of Object.entries(style)) {
    if (v == null || SKIP.has(k) || typeof v === 'object' || typeof v === 'function' || Number.isNaN(v)) continue
    if (typeof v === 'string' && /NaN|undefined/.test(v)) continue
    const value = cssValue(k, v, colors)
    for (const prop of EXPAND[k] || [kebab(k)]) out.push(`  ${prop}: ${value};`)
  }
  if ('flexDirection' in style || 'alignItems' in style || 'justifyContent' in style || 'gap' in style) out.unshift('  display: flex;')
  return out
}

function cssValue(k, v, colors) {
  if (typeof v === 'number') return UNITLESS.has(k) ? String(v) : `${v}px`
  const s = String(v)
  const token = colors.get(s.toLowerCase())
  return token ? `var(${token})` : s
}
